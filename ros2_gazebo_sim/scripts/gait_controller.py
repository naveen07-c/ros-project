#!/usr/bin/env python3
"""
ZMP-preview-control walking controller for the biped.

This implements the standard humanoid walking architecture used on
position-controlled robots (HRP-2 / Atlas style):

  1. Walking pattern generator
     The robot is modelled as a Linear Inverted Pendulum Model (LIPM) with
     natural frequency w = sqrt(g / z_c). The centre of mass (CoM) trajectory
     is generated by *preview control of the Zero Moment Point (ZMP)*
     (Kajita et al., ICRA 2003): the controller looks ahead over a preview
     horizon at the reference ZMP (which is placed inside the support foot)
     and computes a CoM trajectory whose induced ZMP tracks that reference.
     This guarantees the ZMP stays inside the support polygon -> the robot is
     dynamically balanced while it walks.

  2. Footstep / ZMP schedule
     Feet alternate between the two sides; the reference ZMP is held at the
     stance foot during single support and ramps smoothly to the next foot
     during double support.

  3. Divergent Component of Motion (DCM) stabiliser
     The DCM (capture point) xi = com + com_dot / w is compared with the
     reference; any error is fed back as an offset on the commanded CoM
     (Englsberger et al. / Morisawa et al. DCM feedback), making the walk
     robust to disturbances.

  4. Inverse kinematics
     The planned CoM (pelvis) and the planned footholds are converted to the
     ten joint angles by 2-link leg IK and streamed to ``leg_controller``.

If the preview model is not available (no numpy) the node falls back to the
simple sinusoidal kinematic gait.
"""

import math

import numpy as np
import rclpy
from rclpy.node import Node
from nav_msgs.msg import Odometry
from sensor_msgs.msg import JointState
from trajectory_msgs.msg import JointTrajectory, JointTrajectoryPoint

JOINTS = [
    'left_hip_roll', 'right_hip_roll',
    'left_hip_pitch', 'right_hip_pitch',
    'left_knee_pitch', 'right_knee_pitch',
    'left_ankle_pitch', 'right_ankle_pitch',
    'left_ankle_roll', 'right_ankle_roll',
]

SIDES = ('left', 'right')
SIGN = {'left': 1.0, 'right': -1.0}

L1 = 0.30          # thigh length
L2 = 0.30          # shin length
ANKLE_TO_SOLE = 0.06
HIP_Z = -0.02      # hip offset below the base origin
HIP_Y = 0.085      # lateral hip offset
FOOT_HALF = 0.09   # half foot length (front/back edge offset)
G = 9.81


def _clamp(v, lo, hi):
    return max(lo, min(hi, v))


def _smoothstep(u):
    u = _clamp(u, 0.0, 1.0)
    return u * u * (3.0 - 2.0 * u)


def _rpy_from_quat(q):
    x, y, z, w = q.x, q.y, q.z, q.w
    sinr = 2.0 * (w * x + y * z)
    cosr = 1.0 - 2.0 * (x * x + y * y)
    roll = math.atan2(sinr, cosr)
    sinp = 2.0 * (w * y - z * x)
    pitch = math.asin(_clamp(sinp, -1.0, 1.0))
    return roll, pitch


def leg_ik(x, y, z):
    """Inverse kinematics for one leg.

    (x, y, z) is the ankle target relative to the hip, in the base frame
    (z points up, so z is negative when the foot is below the hip).
    Returns (hip_roll, hip_pitch, knee_pitch, ankle_pitch).
    """
    zp = -math.sqrt(y * y + z * z)
    xp = x

    d = math.hypot(xp, zp)
    d = _clamp(d, abs(L1 - L2) + 1e-4, L1 + L2 - 1e-4)

    cos_knee = (d * d - L1 * L1 - L2 * L2) / (2.0 * L1 * L2)
    knee = math.acos(_clamp(cos_knee, -1.0, 1.0))

    X = -xp
    Z = -zp
    hip_pitch = math.atan2(X, Z) - math.atan2(
        L2 * math.sin(knee), L1 + L2 * math.cos(knee))

    hip_roll = math.atan2(y, -zp)
    ankle_pitch = -(hip_pitch + knee)
    return hip_roll, hip_pitch, knee, ankle_pitch


class PreviewControl:
    """Discrete LIPM ZMP preview controller for one axis (Kajita 2003).

    State x = [com, com_dot, com_ddot], input u = com_jerk, output = ZMP.
    """

    def __init__(self, zc, ts, nl, qe=1.0, r=1e-6):
        self.ts = ts
        self.nl = nl
        w = math.sqrt(G / zc)
        self.w = w
        self.A = np.array([[1.0, ts, ts * ts / 2.0],
                           [0.0, 1.0, ts],
                           [0.0, 0.0, 1.0]])
        self.B = np.array([[ts ** 3 / 6.0], [ts * ts / 2.0], [ts]])
        self.C = np.array([[1.0, 0.0, -1.0 / (w * w)]])
        Q = self.C.T @ self.C * qe
        R = np.array([[r]])
        P = Q.copy()
        for _ in range(200000):
            inv = np.linalg.inv(R + self.B.T @ P @ self.B)
            Pn = self.A.T @ P @ self.A - \
                self.A.T @ P @ self.B @ inv @ self.B.T @ P @ self.A + Q
            if np.max(np.abs(Pn - P)) < 1e-13:
                P = Pn
                break
            P = Pn
        self.K = (np.linalg.inv(R + self.B.T @ P @ self.B)
                  @ self.B.T @ P @ self.A).ravel()
        Ac = self.A - self.B @ self.K.reshape(1, 3)
        inv = np.linalg.inv(R + self.B.T @ P @ self.B)
        self.F = np.zeros(nl)
        for i in range(nl):
            self.F[i] = (inv @ self.B.T @
                         np.linalg.matrix_power(Ac.T, i) @ self.C.T * qe).item()
        self.x = np.zeros(3)

    def reset(self, com=0.0):
        self.x = np.array([com, 0.0, 0.0])

    def step(self, zmp_ref):
        """Open-loop advance one tick; ``zmp_ref`` is the future ZMP."""
        u = -self.K @ self.x + self.F @ zmp_ref
        self.x = self.A @ self.x + self.B.ravel() * u
        return self.x[0], self.x[1]

    def servo(self, x_meas, zmp_ref):
        """Closed-loop (servo) step from a measured state.

        Re-seeding the state from the robot every tick removes the drift of
        the open-loop integration and turns the LQR term into real feedback.
        """
        x_meas = np.asarray(x_meas, dtype=float)
        u = -self.K @ x_meas + self.F @ zmp_ref
        xn = self.A @ x_meas + self.B.ravel() * u
        self.x = xn
        return xn

    def zmp(self):
        return self.x[0] - self.x[2] / (self.w * self.w)


class GaitController(Node):
    def __init__(self):
        super().__init__('gait_controller')

        self.declare_parameter('walk_enable', True)
        self.declare_parameter('base_height', 0.64)
        self.declare_parameter('speed', 0.10)
        self.declare_parameter('step_time', 0.8)      # s per step (half cycle)
        self.declare_parameter('ds_frac', 0.30)       # double-support fraction
        self.declare_parameter('step_width', 0.09)
        self.declare_parameter('foot_lift', 0.04)
        self.declare_parameter('stand_time', 2.0)
        self.declare_parameter('prep_time', 1.0)
        self.declare_parameter('publish_rate', 100.0)
        self.declare_parameter('preview_time', 1.6)
        self.declare_parameter('qe', 1.0)
        self.declare_parameter('preview_r', 1e-6)
        self.declare_parameter('servo', False)        # closed-loop preview
        self.declare_parameter('att_fb', True)        # attitude (roll/pitch) FB
        self.declare_parameter('kp_roll', 0.25)
        self.declare_parameter('kd_roll', 0.05)
        self.declare_parameter('roll_sign', -1.0)
        self.declare_parameter('kp_pitch', 0.0)
        self.declare_parameter('kd_pitch', 0.0)
        self.declare_parameter('pitch_sign', 1.0)
        self.declare_parameter('kdcm', 0.0)           # DCM feedback gain
        self.declare_parameter('stand_com_x', 0.0)    # CoM offset while standing
        self.declare_parameter('stand_com_y', 0.0)
        self.declare_parameter('slope_follow', True)  # adapt to ramps
        self.declare_parameter('terrain_x', '')       # comma-sep ground breakpoints
        self.declare_parameter('terrain_z', '')       # matching heights (m)
        self.declare_parameter('ankle_slope_sign', 1.0)  # sole-flatten sign
        self.declare_parameter('slope_zmp_gain', 1.0)  # uphill ZMP lean scale
        self.declare_parameter('slope_speed_factor', 0.5)  # stride scale uphill
        self.declare_parameter('slope_down_factor', 1.0)   # stride scale downhill
        self.declare_parameter('slope_speed_thresh', 0.03)  # |slope| above which to slow
        self.declare_parameter('slope_roll_kp', 0.0)   # extra roll P per slope
        self.declare_parameter('slope_roll_kd', 0.0)   # extra roll D per slope
        self.declare_parameter('slope_roll_cut', 0.0)  # cut base kp_roll on ramps
        self.declare_parameter('slope_kdcm', 0.0)      # slope-gated DCM brake
        self.declare_parameter('step_adj', 0.0)        # DCM footstep-adjust gain
        self.declare_parameter('step_adj_max', 0.03)   # max step adjustment (m)
        self.declare_parameter('roll_direct_kp', 0.5)  # direct hip-roll feedback (fast lateral balance)
        self.declare_parameter('roll_direct_kd', 0.3)  # direct hip-roll rate damping
        # ---- payload-aware CoM model --------------------------------
        # A mass carried on top of the pelvis changes the CoM height (hence the
        # LIPM pendulum length) and, if off-centre, its horizontal position.
        # These mirror the <link name="payload"> in the URDF.
        self.declare_parameter('payload_mass', 0.0)    # kg, centred on base
        self.declare_parameter('payload_x', 0.0)       # position in base frame
        self.declare_parameter('payload_y', 0.0)
        self.declare_parameter('payload_z', 0.05)      # above base origin
        self.declare_parameter('body_mass', 6.3)       # robot without payload
        self.declare_parameter('body_com_height', 0.464)  # body CoM height (m)
        # ---- fall-safe edge guard ------------------------------------
        # The terrain map (terrain_x/terrain_z) is probed ahead of the base; a
        # down-step larger than ``edge_drop`` (a cliff / drop-off) latches the
        # gait to a stop at the end of the current step so the robot halts
        # safely before the edge instead of walking off it.
        self.declare_parameter('edge_stop', True)
        self.declare_parameter('edge_lookahead', 0.30)  # probe distance ahead (m)
        self.declare_parameter('edge_drop', 0.15)       # triggering drop (m)
        # Demo stop: after climbing onto the top platform, keep walking for
        # ``stop_after_climb`` seconds, then halt at the end of that step so a
        # demo ends with the robot standing on top instead of walking off the
        # far edge (0 disables).
        self.declare_parameter('stop_after_climb', 0.0)  # s (0 = disabled)
        self.declare_parameter('climb_z', 0.14)          # top platform height (m)

        rate = self.get_parameter('publish_rate').value
        self.ts = 1.0 / rate
        base_h = self.get_parameter('base_height').value

        # Payload-aware CoM: height above ground and horizontal offset in the
        # base (upright) frame. The LIPM pendulum length scales the nominal
        # base height by the same ratio so the tuned gait stays consistent.
        m_b = self.get_parameter('body_mass').value
        m_p = self.get_parameter('payload_mass').value
        com_b = self.get_parameter('body_com_height').value
        px = self.get_parameter('payload_x').value
        py = self.get_parameter('payload_y').value
        pz = self.get_parameter('payload_z').value
        self._mass = max(1e-6, m_b + m_p)
        com_h = (m_b * com_b + m_p * (base_h + pz)) / self._mass
        self._com_dx = m_p * px / self._mass
        self._com_dy = m_p * py / self._mass
        self._com_height = com_h
        zc = base_h * (com_h / max(1e-6, com_b))
        self._zc = zc
        self.get_logger().info(
            f'payload: m_p={m_p:.2f} kg at ({px:+.3f},{py:+.3f},{pz:+.3f}) '
            f'-> CoM height {com_h:.4f} m (body {com_b:.4f}), '
            f'offset ({self._com_dx:+.4f},{self._com_dy:+.4f}), '
            f'LIPM zc={zc:.4f} (was {base_h:.4f})')
        self._qe = self.get_parameter('qe').value
        self._preview_r = self.get_parameter('preview_r').value
        nl = max(1, int(self.get_parameter('preview_time').value / self.ts))
        self.pc_x = PreviewControl(zc, self.ts, nl, self._qe, self._preview_r)
        self.pc_y = PreviewControl(zc, self.ts, nl, self._qe, self._preview_r)

        self.joint_state = None
        self.roll = 0.0
        self.pitch = 0.0
        self.yaw = 0.0
        self.roll_rate = 0.0
        self.pitch_rate = 0.0
        self.odom_x = 0.0
        self.odom_y = 0.0
        self.odom_z = 0.0
        self.slope = 0.0
        self.base_h_s = 0.0      # rate-limited base-height reference
        self._terrain_cache = None
        self._fh = None          # slope-aware foothold positions
        self.vx = 0.0
        self.vy = 0.0
        self.ax = 0.0
        self.ay = 0.0
        self._last_v = None
        self._last_rpy = None
        self._last_odom = None

        # Warm the preview model up to its periodic solution once at start-up so
        # the pre-walk lateral shift targets the steady sway peak rather than the
        # full step width (avoids the start-up veer/overshoot).
        self.prep_y = 0.0
        self.foot_adj = {}
        self._warm_start()

        self.pub = self.create_publisher(
            JointTrajectory, '/leg_controller/joint_trajectory', 10)
        self.create_subscription(
            JointState, '/joint_states', self._on_joint_state, 10)
        self.create_subscription(Odometry, '/odom', self._on_odom, 10)

        self.start = None
        self.last_t = None
        self.gait_t = 0.0
        self.hold = False       # edge guard latched: freeze the gait schedule
        self.hold_tau = 0.0     # gait time to freeze at (end of a step)
        self._edge_logged = False
        self._climb_t = None    # gait time the top platform was first reached
        self._last_log = 0.0
        self._last_dbg = 0.0
        self.create_timer(self.ts, self._update)
        self.get_logger().info(
            f'ZMP-preview gait_controller ready (nl={nl}, w={self.pc_x.w:.2f})')

    def _on_joint_state(self, msg: JointState):
        self.joint_state = msg

    def _on_odom(self, msg: Odometry):
        roll, pitch = _rpy_from_quat(msg.pose.pose.orientation)
        q = msg.pose.pose.orientation
        self.yaw = math.atan2(2.0 * (q.w * q.z + q.x * q.y),
                              1.0 - 2.0 * (q.y * q.y + q.z * q.z))
        now = self.get_clock().now().nanoseconds * 1e-9
        if self._last_rpy is not None and now > self._last_rpy[2]:
            dt = now - self._last_rpy[2]
            if dt > 1e-4:
                # Low-pass the raw finite-difference rates: the odometry
                # orientation is noisy, so an unfiltered derivative spikes on a
                # single bad sample and the attitude-feedback gains turn that
                # spike into a huge CoM command (the "pop" that topples the
                # robot).  The EMA keeps the meaningful low-frequency rate.
                a = 0.15
                rr = _clamp((roll - self._last_rpy[0]) / dt, -20.0, 20.0)
                pr = _clamp((pitch - self._last_rpy[1]) / dt, -20.0, 20.0)
                self.roll_rate += a * (rr - self.roll_rate)
                self.pitch_rate += a * (pr - self.pitch_rate)
        self.roll = roll
        self.pitch = pitch
        self.odom_x = msg.pose.pose.position.x
        self.odom_y = msg.pose.pose.position.y
        self.odom_z = msg.pose.pose.position.z
        if self._last_odom is not None:
            ox, oy, oz, ot = self._last_odom
            if now > ot:
                dt = now - ot
                self.vx += 0.15 * ((self.odom_x - ox) / dt - self.vx)
                self.vy += 0.15 * ((self.odom_y - oy) / dt - self.vy)
                if self._last_v is not None:
                    lvx, lvy, lt = self._last_v
                    if now > lt:
                        dtt = now - lt
                        self.ax += 0.10 * ((self.vx - lvx) / dtt - self.ax)
                        self.ay += 0.10 * ((self.vy - lvy) / dtt - self.ay)
                self._last_v = (self.vx, self.vy, now)
        self._last_odom = (self.odom_x, self.odom_y, self.odom_z, now)
        self._last_rpy = (roll, pitch, now)

    def _param(self, name):
        return self.get_parameter(name).value

    def _terrain(self):
        """Terrain breakpoints (x, z) parsed from parameters (empty = flat)."""
        if self._terrain_cache is None:
            xs = self._param('terrain_x')
            zs = self._param('terrain_z')
            try:
                xs = [float(v) for v in xs.split(',') if v.strip()]
                zs = [float(v) for v in zs.split(',') if v.strip()]
            except (ValueError, AttributeError):
                xs, zs = [], []
            if len(xs) != len(zs) or len(xs) < 2:
                xs, zs = [], []
            self._terrain_cache = (xs, zs)
        return self._terrain_cache

    def _ground(self, x):
        """Ground height at world x from the terrain map (0 on flat ground).

        Consecutive break-points sharing the same x are treated as a vertical
        riser (a stair step): the upper tread height is returned for x past it.
        """
        xs, zs = self._terrain()
        if not xs:
            return 0.0
        if x <= xs[0]:
            return zs[0]
        if x >= xs[-1]:
            return zs[-1]
        for i in range(1, len(xs)):
            if x <= xs[i]:
                dx = xs[i] - xs[i - 1]
                if dx < 1e-9:
                    return zs[i]
                u = (x - xs[i - 1]) / dx
                return zs[i - 1] + (zs[i] - zs[i - 1]) * u
        return zs[-1]

    def _ground_slope(self, x):
        """Local ground slope dz/dx averaged over the foot span at x."""
        return (self._ground(x + FOOT_HALF) - self._ground(x - FOOT_HALF)) \
            / (2.0 * FOOT_HALF)

    def _has_riser(self):
        """True if the terrain map contains a vertical riser (a stair step)."""
        xs, zs = self._terrain()
        for i in range(1, len(xs)):
            if abs(xs[i] - xs[i - 1]) < 1e-9 and abs(zs[i] - zs[i - 1]) > 1e-9:
                return True
        return False

    def _straddles_riser(self, x):
        """True if a foot centred at x has a stair riser inside its span."""
        xs, zs = self._terrain()
        for i in range(1, len(xs)):
            if abs(xs[i] - xs[i - 1]) < 1e-9 and abs(zs[i] - zs[i - 1]) > 1e-9:
                if x - FOOT_HALF < xs[i] < x + FOOT_HALF:
                    return True
        return False

    def _snap(self, x):
        """Shift a foothold so the foot never straddles a terrain break.

        A break is a stair riser or a grade change (a ramp crest/toe).  A foot
        whose span crosses one is moved entirely onto the nearer side so it
        lands flat and fully supported; a foot left half on the platform and
        half over a ramp hits the edge and rocks.  Flat ground is untouched.
        """
        if not self._param('slope_follow'):
            return x
        xr = self._straddles_break(x)
        if xr is None:
            return x
        f = FOOT_HALF
        m = 0.015  # keep the sole a little back from the edge
        lo = xr - f - m
        hi = xr + f + m
        return lo if abs(x - lo) <= abs(x - hi) else hi

    def _warm_start(self):
        prep = self._param('prep_time')
        T = self._param('step_time')
        cycle_ticks = max(1, int(round(2.0 * T / self.ts)))
        # Converge the preview model to its periodic solution and record the
        # steady lateral sway envelope (this is what a settled walk looks like).
        tau = prep
        self.pc_y.step(self._horizon(tau, self.pc_y, 1))
        peak = 0.0
        for i in range(12 * cycle_ticks):
            tau += self.ts
            cy, _ = self.pc_y.step(self._horizon(tau, self.pc_y, 1))
            if i >= 11 * cycle_ticks:
                peak = max(peak, abs(cy))
        peak = peak if peak > 1e-4 else self._param('step_width')
        # The preview controller looks ahead to the first step (ZMP on the
        # stance foot) during the prep, so parking the CoM at the steady peak
        # would overshoot it. Solve for the prep target that makes the entry's
        # first sway peak match the steady peak (removing the start-up veer).
        target = peak
        for _ in range(3):
            target -= (self._entry_peak(target) - peak)
        self.prep_y = _clamp(target, 0.0, self._param('step_width'))
        self.get_logger().info(
            f'warm start: steady peak={peak:+.4f} prep target={self.prep_y:+.4f}')

    def _entry_peak(self, target):
        """Peak lateral CoM reached during a from-rest entry with this target."""
        self.prep_y = target
        pc = PreviewControl(self._zc, self.ts, self.pc_y.nl,
                            self._qe, self._preview_r)
        prep = self._param('prep_time')
        T = self._param('step_time')
        n = int(round((prep + 1.5 * T) / self.ts))
        tau = 0.0
        peak = 0.0
        for _ in range(n):
            tau += self.ts
            cy, _ = pc.step(self._horizon(tau, pc, 1))
            peak = max(peak, cy)
        return peak

    # ---- footstep / ZMP schedule (straight walking) ---------------------
    def _build_footholds(self):
        """Foothold x positions with a slope-aware stride.

        The nominal stride is ``speed*step_time`` on level ground.  On a
        genuine incline (a ramp, not a stair riser) the stride is shortened by
        ``slope_speed_factor`` so the robot descends at a slower, dynamically
        stable speed without changing the flat/stairs cadence.  The map is
        static, so this is precomputed once.
        """
        sl = self._param('speed') * self._param('step_time')
        fac = _clamp(self._param('slope_speed_factor'), 0.05, 1.0)
        th = max(1e-6, self._param('slope_speed_thresh'))
        # Ramp the stride smoothly from full speed to ``fac`` as the local
        # slope grows from ``th`` to 0.10, so the crest does not cause a step
        # change in the foothold spacing (which would excite the sway).
        full = max(th + 1e-6, 0.10)
        self._fh = [0.0]
        x = 0.0
        dfac = _clamp(self._param('slope_down_factor'), 0.05, 3.0)
        for _ in range(4000):
            # On a descent the body is dragged downhill by gravity, so the
            # feet must keep advancing or the CoM overruns the support and the
            # robot tips over the toe.  Shortening the stride is therefore
            # safe only uphill; downhill use ``slope_down_factor`` (>=1 keeps
            # the feet ahead).  The downhill case keys off the LOCAL ground,
            # not the forward-looking window: applying a long stride on the
            # flat approach to a crest would outrun the body and topple it
            # backwards.
            s_lo = self._ground_slope(x)
            if s_lo < -th:
                u = _clamp((abs(s_lo) - th) / (full - th), 0.0, 1.0)
                fac_s = dfac
            else:
                # Uphill/flat: pre-slow using the look-ahead, but only for a
                # POSITIVE (uphill) slope.  Looking ahead to a descent would
                # shorten the flat approach strides and then jump to the long
                # downhill stride right at the crest.
                s_sp = self._speed_slope(x)
                a = max(abs(s_lo), max(0.0, s_sp))
                u = _clamp((a - th) / (full - th), 0.0, 1.0)
                fac_s = fac
            r = 1.0 + (fac_s - 1.0) * _smoothstep(u)
            nx = self._snap(x + sl * r)
            if nx <= x + 0.005:
                # The nearest clear spot is behind us; hop over the break so
                # consecutive footholds never collapse onto one another.
                b = self._straddles_break(x + sl * r)
                nx = (b + FOOT_HALF + 0.015) if b is not None else (x + 0.005)
            x = nx
            self._fh.append(x)

    def _break_in(self, lo, hi):
        """First terrain break (riser or grade change) inside (lo, hi)."""
        xs, zs = self._terrain()
        prev_s = None
        for i in range(1, len(xs)):
            dx = xs[i] - xs[i - 1]
            dz = zs[i] - zs[i - 1]
            if dx < 1e-9:
                # A duplicated x with dz=0 is just how a ramp corner is
                # encoded (platform edge + ramp start); it is transparent to
                # the slope continuity, so keep prev_s.  Only a genuine
                # vertical riser breaks the continuity.
                if abs(dz) > 1e-9:
                    if lo < xs[i] < hi:
                        return xs[i]
                    prev_s = None
                continue
            s = dz / dx
            if prev_s is not None and abs(s - prev_s) > 0.02:
                if lo < xs[i - 1] < hi:
                    return xs[i - 1]
            prev_s = s
        return None

    def _riser_in(self, lo, hi):
        """True if a genuine vertical riser lies inside (lo, hi)."""
        xs, zs = self._terrain()
        for i in range(1, len(xs)):
            if abs(xs[i] - xs[i - 1]) < 1e-9 and abs(zs[i] - zs[i - 1]) > 1e-9:
                if lo < xs[i] < hi:
                    return True
        return False

    def _slope_mag(self, x):
        """|slope| of genuine ramp ground; 0 on flat ground or near a riser.

        On stairs ``_ground_slope`` straddles a riser and reports a spurious
        slope, so anything slope-gated must be disabled there to leave the
        verified stair gait untouched.
        """
        if not self._param('slope_follow'):
            return 0.0
        if self._riser_in(x - 0.25, x + 0.25):
            return 0.0
        return abs(self._ground_slope(x))

    def _straddles_break(self, x):
        """Break (riser or crest/toe) inside a foot centred at x, or None."""
        return self._break_in(x - FOOT_HALF, x + FOOT_HALF)

    def _speed_slope(self, x):
        """Slope used to decide the stride shortening (looks ahead on ramps).

        Uses a long, forward-biased baseline so the robot is already slow when
        it reaches a ramp crest; returns 0 when any break (stair riser or a
        flat/ramp crest) lies in the window, so the stride does not bunch the
        footholds up against the break.
        """
        lo, hi = x - 0.05, x + 0.35
        if self._riser_in(lo, hi):
            # Stairs are tuned at full cadence; a riser in the window must not
            # trigger the ramp slowdown (its tread slope is meaningless).
            return 0.0
        if self._break_in(lo, hi) is not None:
            # Crest or toe inside the window: the far baseline straddles the
            # break and averages the slope away, so take the steepest of the
            # near (behind the break) and far (beyond it) sides.  This keeps
            # the slowdown active on the approach to a crest and on the ramp
            # itself when the toe is ahead.
            s_near = (self._ground(x + 0.02)
                      - self._ground(lo + 0.02)) / max(1e-6, x - lo)
            s_far = (self._ground(hi) - self._ground(hi - 0.05)) / 0.05
            return s_far if abs(s_far) > abs(s_near) else s_near
        return (self._ground(hi) - self._ground(lo)) / (hi - lo)

    def _foot(self, k):
        """Nominal world position of foothold k (k may be -1)."""
        if self._fh is None:
            self._build_footholds()
        wy = self._param('step_width')
        kk = min(max(0, k), len(self._fh) - 1)
        x = self._snap(max(0.0, self._fh[kk]))
        y = wy if (k % 2 == 0) else -wy
        return x, y

    def _ffoot(self, k):
        """Foothold k including the reactive step adjustment (physical foot)."""
        x, y = self._foot(k)
        dx, dy = self.foot_adj.get(k, (0.0, 0.0))
        return x + dx, y + dy

    def _zmp_ref(self, tau):
        """Reference ZMP (x, y) at gait time ``tau``."""
        prep = self._param('prep_time')
        if tau < prep:
            # Both feet planted while the CoM ramps onto the steady-state
            # start-of-step state (see _update); keep the ZMP at that state.
            return 0.0, self.prep_y
        tau = tau - prep
        T = self._param('step_time')
        T_ss = T * (1.0 - self._param('ds_frac'))
        k = int(math.floor(tau / T))
        phi = tau - k * T
        fx, fy = self._ffoot(k)
        nx, ny = self._ffoot(k + 1)
        if phi < T_ss:
            return fx + self._slope_shift(fx), fy
        u = _smoothstep((phi - T_ss) / max(1e-6, T - T_ss))
        return (fx + (nx - fx) * u + self._slope_shift(fx),
                fy + (ny - fy) * u)

    def _slope_shift(self, x):
        """Uphill ZMP-reference offset needed to lean into a slope.

        On an incline the CoM settles ``z_c*sin(alpha)`` uphill of the ZMP
        (so its vertical projection stays over the foot). Shifting the ZMP
        reference by that amount yields exactly that equilibrium.
        """
        if not self._param('slope_follow'):
            return 0.0
        # A foothold straddling a stair riser reports a huge spurious slope;
        # applying the lean there shoves the ZMP reference off the foot.  Only
        # lean on genuine (ramp) ground.
        if self._straddles_riser(x):
            return 0.0
        s = self._ground_slope(x)
        return self._param('slope_zmp_gain') * self._zc * s / math.sqrt(1.0 + s * s)


    def _horizon(self, tau, pc, axis):
        return np.array([
            (self._zmp_ref(tau + i * self.ts)[axis])
            for i in range(pc.nl)
        ])

    def _update(self):
        if self.joint_state is None:
            return

        now = self.get_clock().now()
        t = now.nanoseconds * 1e-9
        if self.start is None:
            self.start = t
            self.last_t = t
        dt = max(0.0, min(0.05, t - self.last_t))
        self.last_t = t
        elapsed = t - self.start

        H = self._param('base_height')
        stance_w = self._param('step_width')
        foot_lift = self._param('foot_lift')
        stand_time = self._param('stand_time')
        step_time = self._param('step_time')
        ds_frac = self._param('ds_frac')
        kdcm = self._param('kdcm')
        T_ss = step_time * (1.0 - ds_frac)

        walking = self._param('walk_enable') and elapsed >= stand_time

        # Fall-safe edge guard: probe the terrain map ahead of the base.  A
        # drop larger than ``edge_drop`` latches a stop at the end of the
        # current step, so the robot plants both feet and halts before the edge.
        if walking and self._param('edge_stop') and not self.hold:
            here = self._ground(self.odom_x)
            ahead = self._ground(self.odom_x + self._param('edge_lookahead'))
            if here - ahead >= self._param('edge_drop'):
                self.hold = True
                prep = self._param('prep_time')
                if self.gait_t > prep:
                    k = int(math.floor((self.gait_t - prep) / step_time))
                    self.hold_tau = prep + (k + 1) * step_time
                else:
                    self.hold_tau = prep
                if not self._edge_logged:
                    self._edge_logged = True
                    self.get_logger().warn(
                        f'EDGE ahead: drop={here - ahead:.3f} m at '
                        f'x={self.odom_x + self._param("edge_lookahead"):+.3f}; '
                        f'halting at x~{self.odom_x:+.3f}')

        # Demo stop: once the feet are on the top platform, walk on for
        # ``stop_after_climb`` seconds and then hold at the end of the current
        # step (both feet planted).  This keeps a demo from walking off the far
        # edge of the platform.
        soc = self._param('stop_after_climb')
        if walking and soc > 0.0 and not self.hold:
            if self._climb_t is None:
                if self._ground(self.odom_x) >= self._param('climb_z'):
                    self._climb_t = self.gait_t
                    self.get_logger().info(
                        f'CLIMBED at x={self.odom_x:+.3f}; '
                        f'stopping in {soc:.1f} s')
            elif self.gait_t - self._climb_t >= soc:
                prep = self._param('prep_time')
                if self.gait_t > prep:
                    k = int(math.floor((self.gait_t - prep) / step_time))
                    self.hold_tau = prep + (k + 1) * step_time
                else:
                    self.hold_tau = prep
                self.hold = True
                self.get_logger().warn(
                    f'DEMO STOP: on top at x~{self.odom_x:+.3f} '
                    f'(gz={self._ground(self.odom_x):.3f}); holding')

        if walking:
            if self.hold:
                self.gait_t = min(self.gait_t + self.ts, self.hold_tau)
            else:
                self.gait_t += self.ts
            tau = self.gait_t
            zx = self._horizon(tau, self.pc_x, 0)
            zy = self._horizon(tau, self.pc_y, 1)
            if self._param('servo'):
                nx = self.pc_x.servo([self.odom_x, self.vx, self.ax], zx)
                ny = self.pc_y.servo([self.odom_y, self.vy, self.ay], zy)
                cx, cvx = nx[0], nx[1]
                cy, cvy = ny[0], ny[1]
            else:
                cx, cvx = self.pc_x.step(zx)
                cy, cvy = self.pc_y.step(zy)
        else:
            tau = 0.0
            cx = self._param('stand_com_x') - self._com_dx
            cy = self._param('stand_com_y') - self._com_dy
            cvx = cvy = 0.0
            self.pc_x.reset(cx)
            self.pc_y.reset(cy)

        # Attitude feedback: the preview plan is feed-forward only, so add a
        # roll/pitch stabiliser (the proven lateral-balance term) to reject
        # tracking errors before the unstable LIPM mode diverges.
        if walking and self._param('att_fb'):
            cx += self._param('pitch_sign') * (
                self._param('kp_pitch') * self.pitch +
                self._param('kd_pitch') * self.pitch_rate)
            slope_mag = self._slope_mag(self.odom_x)
            # On a genuine ramp the absolute-roll term acts as positive
            # feedback once the sway is perturbed (it commands the pelvis in
            # the direction of the lean), so fade the P part out there while
            # keeping it on flat ground and stairs, where it is verified.
            cut = self._param('slope_roll_cut') * \
                _smoothstep((slope_mag - 0.02) / 0.08)
            kp_r = (self._param('kp_roll') * (1.0 - cut) +
                    self._param('slope_roll_kp') * slope_mag)
            kd_r = (self._param('kd_roll') +
                    self._param('slope_roll_kd') * slope_mag)
            cy += self._param('roll_sign') * (
                kp_r * self.roll + kd_r * self.roll_rate)

        # DCM feedback: steer the commanded CoM by the capture-point error
        if walking and kdcm != 0.0:
            w = self.pc_x.w
            xi_x = self.odom_x + self.vx / w
            xi_y = self.odom_y + self.vy / w
            ref_x = cx + cvx / w
            ref_y = cy + cvy / w
            cx -= kdcm * (xi_x - ref_x)
            cy -= kdcm * (xi_y - ref_y)

        # Slope-gated capture-point brake: on a descent gravity carries the
        # body downhill faster than the deliberately slow foothold schedule,
        # so pull the commanded CoM back by the DCM tracking error.  Gated to
        # genuine ramps so flat/stairs keep the verified behaviour.
        ksl = self._param('slope_kdcm')
        if walking and ksl != 0.0 and self._slope_mag(self.odom_x) > 0.02:
            w = self.pc_x.w
            xi_x = self.odom_x + self.vx / w
            ref_x = cx + cvx / w
            cx -= ksl * (xi_x - ref_x)

        # Payload CoM offset: the base is commanded so the true CoM (base plus
        # the payload's horizontal offset) tracks the plan, so the ZMP stays
        # under the actual CoM and the ft/ramp balance is preserved.
        if walking:
            cx -= self._com_dx
            cy -= self._com_dy

        # Reactive stepping (capture-point / DCM foot placement): shift the
        # landing foothold by the DCM tracking error so the robot steps to
        # catch itself on a slope lip or after a disturbance.  This is the
        # "landing foot position adjustor" strategy shown to be the robust
        # fix for uneven/inclined terrain.
        if walking and self._param('step_adj') > 0.0:
            prep_adj = self._param('prep_time')
            if tau >= prep_adj:
                kk = int(math.floor((tau - prep_adj) / step_time))
                # Skip the first step: the startup CoM transient would otherwise
                # bias the very first foothold and topple the robot.
                if kk >= 1:
                    w = self.pc_x.w
                    xi_x = self.odom_x + self.vx / w
                    xi_y = self.odom_y + self.vy / w
                    lim = self._param('step_adj_max')
                    g = self._param('step_adj')
                    dx = _clamp(g * (xi_x - (cx + cvx / w)), -lim, lim)
                    dy = _clamp(g * (xi_y - (cy + cvy / w)), -lim, lim)
                    self.foot_adj[kk + 1] = (dx, dy)

        # ---- foot targets ----
        feet = {}
        prep = self._param('prep_time')
        sup_side = None
        if walking and tau < prep:
            for s in SIDES:
                feet[s] = (0.0, SIGN[s] * stance_w, 0.0)
        elif walking:
            tau = tau - prep
            T = step_time
            k = int(math.floor(tau / T))
            phi = tau - k * T
            sup_x, sup_y = self._ffoot(k)
            from_x, from_y = self._ffoot(k - 1)
            to_x, to_y = self._ffoot(k + 1)
            if phi < T_ss:
                u = phi / max(1e-6, T_ss)
                sw_x = from_x + (to_x - from_x) * _smoothstep(u)
                sw_y = from_y + (to_y - from_y) * _smoothstep(u)
                su = _smoothstep(u)
                lift = foot_lift * 4.0 * su * (1.0 - su)
            else:
                sw_x, sw_y, lift = to_x, to_y, 0.0
            sup_side = 'left' if (k % 2 == 0) else 'right'
            for s in SIDES:
                if s == sup_side:
                    feet[s] = (sup_x, sup_y, 0.0)
                else:
                    feet[s] = (sw_x, sw_y, lift)
        else:
            for s in SIDES:
                feet[s] = (0.0, SIGN[s] * stance_w, 0.0)

        positions = {}
        use_terrain = self._param('slope_follow')
        # Base-height reference: follow the SUPPORT foot's tread so the pelvis
        # only rises when the next foot has landed (double support), never
        # mid-swing.  Rate-limit so a riser is a smooth ramp, not a step.
        if use_terrain:
            prep_bh = self._param('prep_time')
            gt = self.gait_t
            if walking and gt >= prep_bh:
                kk_bh = int(math.floor((gt - prep_bh) / step_time))
                tgt_h = self._ground(self._ffoot(kk_bh)[0])
            else:
                tgt_h = self._ground(self.odom_x)
        else:
            tgt_h = 0.0
        step_h = 0.10 * self.ts
        if tgt_h > self.base_h_s:
            self.base_h_s = min(tgt_h, self.base_h_s + step_h)
        else:
            self.base_h_s = max(tgt_h, self.base_h_s - step_h)
        base_h = self.base_h_s
        for s in SIDES:
            fx, fy, lift = feet[s]
            rx = fx - cx
            ry = fy - cy - SIGN[s] * HIP_Y
            # Raise the foothold onto the terrain relative to the ground under
            # the base. The ground is sampled over the foot span (front edge
            # leads) so the sole clears the ramp lip, and the ankle tilt below
            # keeps the sole parallel to the local slope (lands flat, no catch).
            if use_terrain:
                # On a genuine riser straddle the foot must clear the higher
                # edge (max).  Elsewhere (flat treads after snapping, smooth
                # ramps) sample the ground at the foothold centre so the sole
                # rests exactly on the surface instead of floating by
                # FOOT_HALF*slope and dropping in the next step.
                if self._straddles_riser(fx):
                    gz = max(self._ground(fx - FOOT_HALF),
                             self._ground(fx + FOOT_HALF))
                else:
                    gz = self._ground(fx)
                rz = (lift + ANKLE_TO_SOLE + (gz - base_h)) - (H + HIP_Z)
                # On stairs the foot sits on a flat tread, but _ground_slope
                # straddles the riser and reports a spurious slope; tilting the
                # ankle there just jabs the toe/heel into the step.  Only apply
                # the sole-flatten tilt on genuine (ramp) terrain.
                if self._straddles_riser(fx):
                    tilt = 0.0
                else:
                    tilt = self._param('ankle_slope_sign') * \
                        math.atan(self._ground_slope(fx))  # ramp-only tilt
            else:
                rz = (lift + ANKLE_TO_SOLE) - (H + HIP_Z)
                tilt = 0.0
            hip_roll, hip_pitch, knee, ankle_pitch = leg_ik(rx, ry, rz)
            # Direct lateral roll feedback: command hip-roll torque to counter
            # base roll on the stance leg, bypassing the slow ZMP-preview path.
            if sup_side is None or s == sup_side:
                fb = (self._param('roll_direct_kp') * self.roll
                      + self._param('roll_direct_kd') * self.roll_rate)
                hip_roll += fb
            positions[s + '_hip_roll'] = hip_roll
            positions[s + '_hip_pitch'] = hip_pitch
            positions[s + '_knee_pitch'] = knee
            positions[s + '_ankle_pitch'] = ankle_pitch + tilt
            positions[s + '_ankle_roll'] = -hip_roll

        if (t - self._last_log) >= 0.25:
            self._last_log = t
            zx0, zy0 = self._zmp_ref(tau)
            self.get_logger().info(
                f'cx={cx:+.3f} cy={cy:+.3f} ox={self.odom_x:+.3f} '
                f'oy={self.odom_y:+.3f} vx={self.vx:+.3f} vy={self.vy:+.3f} '
                f'zx={zx0:+.3f} zy={zy0:+.3f} '
                f'pitch={self.pitch:+.3f} roll={self.roll:+.3f} '
                f'z={self.odom_z:.3f} gz={self._ground(self.odom_x):.3f} '
                f'sl={self._speed_slope(self.odom_x):+.3f} yaw={self.yaw:+.3f}')

        traj = JointTrajectory()
        traj.header.stamp = now.to_msg()
        traj.joint_names = JOINTS
        point = JointTrajectoryPoint()
        point.positions = [positions[j] for j in JOINTS]
        point.time_from_start.sec = 0
        point.time_from_start.nanosec = 100000000
        traj.points.append(point)
        self.pub.publish(traj)


def main(args=None):
    rclpy.init(args=args)
    node = GaitController()
    try:
        rclpy.spin(node)
    except KeyboardInterrupt:
        pass
    finally:
        node.destroy_node()
        rclpy.shutdown()


if __name__ == '__main__':
    main()
